public enum EffectType {
    FIRE,        // orange/red rising particles — default for RAGED
    ELECTRIC,    // blue/white lightning sparks — default for ADVANTAGE
    AURORA,      // green/teal drifting wisps — default for NORMAL
    VOID,        // dark slow smoke — default for PAUSED
    BLOOD_RAIN,  // red particles falling from top
    PLASMA,      // chaotic multicolor plasma swirl
    MAELSTROM,   // particles spiral inward from edges to center
    SHOCKWAVE    // concentric rings expanding from center on beat
}
